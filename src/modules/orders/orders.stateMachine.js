  SHIPPED: 'SHIPPED',
  OOD: 'OOD', // Out For Delivery
  DELIVERED: 'DELIVERED',
  CANCELLED: 'CANCELLED',
  RTO_INITIATED: 'RTO_INITIATED',
  RTO_DELIVERED: 'RTO_DELIVERED',
